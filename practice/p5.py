def area(width, height = 1):
# 함수 area를 정의(def) 하면서 매개변수 width,height를 필요하고 height는 기본값 1을 작성했네, 자바에서는 반환값이 있으면 리턴 타입을 작성해줘야 되는데
    return width * height # area 함수는 width*height의 값을 리턴해주네

# 자바에서는 인자 개수를 다르게 주려면 메서드 오버로딩 해야되는데
print(area(3,4)) # 12
print(area(3)) # 3(height 기본값 1 때문)

def min_max(nums): # 매개변수 nums를 받네, 파이썬은 아직 nums가 무슨 값을 담는 상자인지 모름
    return min(nums), max(nums) # 뭐지? 받는 인자의 최소와 최대 값을 반환해주는 함수인가? 함수안에 함수라? 그럼 min(),max()는 파이썬에서 기본으로 제공해주는 기본 함수인가?
# min(), max() 내장 함수: 별도로 import 할 필요 없이 파이썬이 기본으로 제공하는 내장 함수(Built-in Function)
# 자바 메서드는 무조건 단 하나의 객체나 값만 반환할 수 있는데, 파이썬은 쉼표(,)로 나열하기만 하면 여러 값을 한 번에 반환
# 내부적으로는 (2, 9)라는 튜플(Tuple) 형태로 묶여서 반환
# 튜플은 "한 번 만들면 안의 값을 절대 바꿀 수 없는(읽기 전용) 리스트"입니다. 소괄호 ()를 사용해 만듭니다.
# 값이 1개일 때는 소괄호만 쓰면 일반 숫자/문자로 인식되므로, 반드시 뒤에 쉼표(,)를 찍어줘야 튜플로 패킹됩니다.
not_tuple = (10)    # 그냥 정수 10 (int)
is_tuple1 = (10,)   # 요소가 1개인 튜플 (tuple)
is_tuple2 = 10,     # 소괄호를 생략해도 쉼표만 있으면 튜플 (tuple)

low, high = min_max([4,9,2]) # 배열을 인자로 줫네?
print(low, high) # 출력: 2 9 (공백 자동 삽입)
# 함수가 반환한 (2, 9) 두 개의 값을 왼쪽의 변수 low와 high가 순서대로 하나씩 나누어 받습니다