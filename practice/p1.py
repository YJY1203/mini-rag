print (type(n)) # 츨력 n의 타입(String?)


print (7/2) # 7 나누기 2  = 3.5 인데, 타입을 자동으로 맞춰 주면 실수로 찍어주나?
print (7//2) # 시부레 // 는 첨보는 연산자 인데?, 설마 공백도 계산? 그럼 에러 나는거 아니야?

name = "RAG" # name 변수에 "RAG" 문자열 대입
print (f"{name}는 {len(name)}글자") # f"..." (포맷 문자열 f-string, "..." 안에 {}이 있어 표현식 계산 가능

# 파이썬은 동적 타이핑(Dynamic Typing)방식이라 에러가 안남. (자바는 타입고정(정적 타이핑))
# '//'는 소수점 이하를 버리고 정수 몫만 구하는 연산자(Floor Division)
# 파이썬은 모든 것이 객체(Object)로 취급, 자주 쓰는 작은 정수(-5 ~ 256)나 짧은 문자열을 미리 힙 메모리에 만들어 두고 재사용(인터닝, Interning)
# 개발자가 타입이나 메모리 크기를 신경 쓰지 않고 빠르게 코딩할 수 있는 편의성을 극대화한 언어, 물론 최적화에는 거리가 멈
