nums = [10,20,30,40,50] # 배열 객체 생성
nums.append(60) # append()는 리스트의 맨 끝에 새 요소를 추가하는 메서드
# 파이썬 리스트는 nums.append("사과")처럼 숫자와 문자를 한 리스트 안에 섞어서 넣을 수 있음

print(nums[0]) # 0번 인덱스 즉 10 출력
print(nums[-1]) # -1은 맨 뒤에서 첫 번째 요소
print(nums[1:3]) # 이건 1부터 3직전까지 출력하라는거, 물론 위치를 뜻하는거 결과는 20,30
print(nums[:2]) # 앞을 비워두면 0부터 시작하는 것. 결과는 10,20
print(len(nums)) # nums의 현재 요소 개수 반환: 6,자바의 nums.length나 list.size()와 같은 역할

text = "abcdefghij"
# 파이썬에서는 문자열도 문자들이 순서대로 나열된 시퀀스(순서형) 데이터로 취급
print(text[0:4]) # text에 담긴 문자열의 문자 하나하나 마다 인덱스를 표현한건가? 그럼 결과는 abcd

a = [1,2]
b = a
b.append(3)
# 실제 데이터 [1, 2]는 힙(Heap) 영역에 하나만 생성
# 변수 a와 b는 각자의 공간에서 같은 힙 메모리 주소를 가리키고 있으
# 주소가 아닌 실제 데이터만 복제해서 독립된 리스트를 만들고 싶다면 b = a.copy() 또는 슬라이싱을 활용한 b = a[:]를 사용
print(a) # 결과: 1,2,3
